@dataclass(frozen=True)
class Term:
    id: str
    sphere: str
    uk: str
    ru: str
    en: str
    patterns: tuple[str, ...] = ()
    category_patterns: tuple[str, ...] = ()
    priority: int = 0
    umbrella: str | None = None  # group name; the term is the general member of the group
    group: str | None = None  # group name for specific members
    names: dict[str, str] = field(init=False, compare=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "names", {"uk": self.uk, "ru": self.ru, "en": self.en})


def T(
    id: str,
    sphere: str,
    uk: str,
    ru: str,
    en: str,
    *patterns: str,
    category: tuple[str, ...] = (),
    priority: int = 0,
    umbrella: str | None = None,
    group: str | None = None,
) -> Term:
    return Term(id, sphere, uk, ru, en, patterns, category, priority, umbrella, group)



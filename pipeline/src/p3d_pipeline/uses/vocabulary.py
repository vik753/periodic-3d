# Terms for what a substance *is* (a drug, a herbicide), not what it goes into. "Used in
# the production of insecticides" does not make chlorine an insecticide.
ROLE_TERMS: frozenset[str] = frozenset(
    term.id
    for term in TERMS
    if term.sphere == "medicine"
    or "pesticide" in (term.group, term.umbrella)
    or term.id in {"plant_growth", "repellent", "chemical_weapons", "riot_control"}
)
SPHERE_BY_ID: dict[str, Sphere] = {sphere.id: sphere for sphere in SPHERES}


def _check() -> None:
    seen: set[str] = set()
    for term in TERMS:
        if term.id in seen:
            raise ValueError(f"duplicate term {term.id}")
        seen.add(term.id)
        if term.sphere not in SPHERE_BY_ID:
            raise ValueError(f"term {term.id}: unknown sphere {term.sphere}")
        for pattern in (*term.patterns, *term.category_patterns):
            re.compile(pattern)


_check()

